#!/usr/bin/env node
/**
 * Measure the reconciler against ground truth (§13 guardrail, §10.2).
 *
 *   node scripts/eval-reconciliation.mjs [--limit 120] [--arm both|accession|label]
 *                                        [--out data/eval/reconciliation.json]
 *                                        [--replay data/eval/reconciliation.json]
 *                                        [--sleep 1200] [--json]
 *
 * Why this exists
 * ---------------
 * §13's guardrail is "catalogue match accuracy below 95% means stop feature
 * work". That number was previously computed from recognition_events, which on a
 * seeded database are generated by scripts/lib/demo.mjs from a hardcoded
 * acceptance rate — so it could not fail, and it measured the seeder rather than
 * the matcher.
 *
 * There is real ground truth available instead. The Met publishes its own
 * Wikidata Q-number per object in the CC0 dump, so 9,971 of the 10,000 catalogued
 * works carry a link the museum asserted itself. That lets the matcher be graded:
 * run it over real works, ask live Wikidata for candidates, and compare what it
 * decided against what the museum says. No users required, and it can fail.
 *
 * Two arms, because they answer different questions
 * -------------------------------------------------
 *   accession  the pipeline exactly as it ships. P217 inventory lookup scoped to
 *              the Met's collection, falling back to labels. This is the number
 *              that describes today's catalogue.
 *   label      the same matcher with the accession withheld, forcing the fuzzy
 *              title/artist/year path. Wikidata's Met inventory numbers largely
 *              came from the Met, so the accession arm partly agrees by
 *              construction; the label arm is the independent measurement, and
 *              it is also the only arm that predicts a source which does *not*
 *              publish Wikidata-linked accession numbers (§10.1's next adapter).
 *
 * Nothing here writes to `works`. Grading a matcher must not also apply its
 * verdicts, or the second run grades the first run's output.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { openDb } from "./lib/db.mjs";
import { scoreCandidate, AUTO_ACCEPT, REVIEW_FLOOR } from "../src/lib/text.mjs";
import { wikidataProvider } from "./ingest/wikidata.mjs";

const DEFAULT_OUT = path.join("data", "eval", "reconciliation.json");

function parseArgs(argv) {
  const args = { limit: 120, arm: "both", out: DEFAULT_OUT, sleep: 1200, json: false };
  for (let i = 2; i < argv.length; i++) {
    const flag = argv[i];
    if (flag === "--limit") args.limit = Number(argv[++i]);
    else if (flag === "--arm") args.arm = argv[++i];
    else if (flag === "--out") args.out = argv[++i];
    else if (flag === "--replay") args.replay = argv[++i];
    else if (flag === "--sleep") args.sleep = Number(argv[++i]);
    else if (flag === "--json") args.json = true;
    else throw new Error(`unknown flag: ${flag}`);
  }
  return args;
}

/**
 * A stratified, deterministic sample: half attributed, half anonymous.
 *
 * Two reasons not to take the first N rows, or even an even stride over all of
 * them. `works` is ordered by the Met's own object id, which correlates with
 * department and accession era — a plain stride lands mostly in antiquities. And
 * 62% of the on-view catalogue has no named artist at all, so an unstratified
 * sample drowns the attributed works that are the only ones the fuzzy path can
 * operate on, and the label arm then reports zero for a structural reason rather
 * than a quality one. Both strata are sampled, and reported separately.
 */
async function sample(db, limit) {
  const half = Math.max(1, Math.round(limit / 2));
  const rowsWhere = (attributed) =>
    db
      .prepare(
        `SELECT w.id, w.title, w.artist_display, w.date_begin, w.wikidata_qid,
                (SELECT value FROM work_identifiers
                  WHERE work_id = w.id AND scheme IN ('met_accession','aic_accession')
                  LIMIT 1) AS accession,
                -- Ground truth is not automatically true. Where the source has
                -- given one Q-number to two objects, at most one of them can be
                -- right, so a disagreement there is not evidence about the matcher.
                (SELECT COUNT(*) FROM works d WHERE d.wikidata_qid = w.wikidata_qid) AS qid_uses,
                ROW_NUMBER() OVER (ORDER BY w.id) AS rn
           FROM works w
          WHERE w.wikidata_qid IS NOT NULL
            AND TRIM(w.artist_display) ${attributed ? "<> ''" : "= ''"}
          ORDER BY w.id`,
      )
      .all();

  const pick = (rows, want) => {
    const stride = Math.max(1, Math.floor(rows.length / Math.max(1, want)));
    return rows.filter((row) => row.rn % stride === 0).slice(0, want);
  };

  const attributedRows = await rowsWhere(true);
  const anonymousRows = await rowsWhere(false);
  return [
    ...pick(attributedRows, half).map((row) => ({ ...row, attributed: true })),
    ...pick(anonymousRows, limit - half).map((row) => ({ ...row, attributed: false })),
  ];
}

/**
 * The shipped decision rule from reconcileWorks(), lifted verbatim.
 *
 * Deliberately duplicated rather than imported: reconcileWorks() writes to the
 * database as it decides, and an evaluation must not. If the rule there changes
 * and this drifts, the drift shows up as an unexplained accuracy change, which
 * is the failure mode a comment cannot prevent — so the assertion below pins the
 * thresholds instead.
 */
function decide(record, candidates) {
  const scored = candidates
    .map((candidate) => ({ candidate, ...scoreCandidate(record, candidate) }))
    .filter((entry) => entry.score >= REVIEW_FLOOR)
    .sort((a, b) => b.score - a.score);

  if (!scored.length) return { outcome: "unmatched", scored };

  const best = scored[0];
  const runnerUp = scored[1];
  const ambiguous =
    Boolean(runnerUp) && best.score - runnerUp.score < 0.05 && best.method !== "accession";

  if (best.score >= AUTO_ACCEPT && !ambiguous) {
    return { outcome: "accepted", qid: best.candidate.qid, method: best.method, score: best.score, scored };
  }
  return { outcome: "queued", ambiguous, scored };
}

/**
 * Persist the candidate cache mid-run.
 *
 * Written to a sidecar rather than the summary file: the summary is the committed
 * artifact the guardrail reads, and a half-finished run must not be mistaken for a
 * measurement. `--replay` reads the sidecar back.
 */
function checkpoint(out, cache, recorded) {
  const file = `${out.replace(/\.json$/, "")}-cache.json`;
  mkdirSync(path.dirname(file), { recursive: true });
  // Merged, not replaced. Writing `recorded` alone silently discarded every
  // answer loaded from a previous run — a one-arm run threw away the other arm's
  // cache and the guardrail lost its measurement.
  writeFileSync(file, JSON.stringify({ candidates: { ...cache, ...recorded } }));
}

/**
 * Fold this run's arms into the committed summary.
 *
 * The guardrail reads `arms.accession` from a fixed path, and the arms are run
 * separately because the label arm is an order of magnitude slower. Replacing the
 * file per run meant measuring one arm deleted the other. Each arm carries its own
 * provenance so a stale one is visible rather than implied.
 */
function mergeSummary(out, result) {
  const existing = existsSync(out) ? JSON.parse(readFileSync(out, "utf8")) : {};
  return {
    ...result,
    arms: { ...(existing.arms ?? {}), ...result.arms },
    conflicts: result.conflicts,
  };
}

function blankTally() {
  return {
    examined: 0,
    accepted: 0,
    acceptedCorrect: 0,
    acceptedWrong: 0,
    queued: 0,
    queuedContainingTruth: 0,
    unmatched: 0,
    errors: 0,
    /** Auto-accepts that disagree with a Q-number the source gave to two objects. */
    groundTruthConflict: 0,
    // Split by attribution: scoreCandidate requires artist similarity ≥ 0.6, so
    // an anonymous work can never clear the floor on the label path however good
    // the title match is. Counting those as misses would blame the matcher for a
    // property of the catalogue.
    attributed: { examined: 0, accepted: 0, acceptedCorrect: 0, acceptedWrong: 0, groundTruthConflict: 0 },
    anonymous: { examined: 0, accepted: 0, acceptedCorrect: 0, acceptedWrong: 0, groundTruthConflict: 0 },
  };
}

/**
 * Of the matches the machine committed to on its own, how many were right.
 *
 * Auto-accepts that landed on a work whose Q-number the source has given to two
 * different objects are excluded from the denominator: there is no answer key for
 * those, so scoring them either way would be inventing one. They are reported
 * separately and are a defect in the catalogue, not in the matcher.
 */
function precision(tally) {
  const judged = tally.accepted - tally.groundTruthConflict;
  return judged > 0 ? tally.acceptedCorrect / judged : null;
}

/** Of everything sampled, how many it both decided and got right. */
function coverage(tally) {
  return tally.examined ? tally.acceptedCorrect / tally.examined : null;
}

async function run() {
  const args = parseArgs(process.argv);
  const arms = args.arm === "both" ? ["accession", "label"] : [args.arm];

  // Replay mode grades a cached run: no network, byte-identical result, which is
  // what makes this usable as a gate rather than a one-off experiment.
  // Replay reads the candidate sidecar; a live run resumes from it, so an
  // interrupted run continues instead of re-paying for every query.
  const cacheFile = `${(args.replay ?? args.out).replace(/\.json$/, "")}-cache.json`;
  const cache = existsSync(cacheFile)
    ? JSON.parse(readFileSync(cacheFile, "utf8")).candidates ?? {}
    : {};
  if (args.replay && !existsSync(cacheFile)) {
    throw new Error(`no cached candidates at ${cacheFile} — run a live eval first`);
  }

  const db = await openDb();
  const works = await sample(db, args.limit);
  await db.close();

  const provider = args.replay ? null : wikidataProvider({ sleepMs: args.sleep });
  const tallies = Object.fromEntries(arms.map((arm) => [arm, blankTally()]));
  const recorded = {};
  const misses = [];
  const conflicts = [];

  let done = 0;
  for (const work of works) {
    if (!args.json && ++done % 10 === 0) {
      process.stderr.write(`  ${done}/${works.length} works\n`);
    }
    for (const arm of arms) {
      const tally = tallies[arm];
      tally.examined++;

      const record = {
        title: work.title,
        artist: work.artist_display,
        year: work.date_begin,
        // The whole point of the label arm: withhold the identifier that makes
        // it easy and see whether the matcher still lands on the same object.
        accession: arm === "accession" ? work.accession : null,
      };

      const key = `${arm}:${work.id}`;
      let candidates = cache[key] ?? recorded[key];
      if (!candidates) {
        if (!provider) {
          tally.examined--;
          continue;
        }
        try {
          candidates = await provider.search(record);
        } catch (error) {
          // WDQS is a shared volunteer endpoint and the label query (mwapi
          // EntitySearch) times out under load. One 504 must not cost the run.
          tally.errors++;
          process.stderr.write(`  ${arm} ${work.id}: ${error.message}\n`);
          continue;
        }
        // Checkpoint every answer. A live run takes tens of minutes against a
        // rate-limited endpoint; writing only at the end means one timeout or one
        // Ctrl-C throws away every query already paid for.
        recorded[key] = candidates;
        checkpoint(args.out, cache, recorded);
      }
      recorded[key] = candidates;

      const verdict = decide(record, candidates);
      const truth = work.wikidata_qid;
      const stratum = work.attributed ? tally.attributed : tally.anonymous;
      stratum.examined++;

      if (verdict.outcome === "accepted") {
        tally.accepted++;
        stratum.accepted++;
        if (verdict.qid === truth) {
          tally.acceptedCorrect++;
          stratum.acceptedCorrect++;
        } else if (work.qid_uses > 1) {
          // The source gave this Q-number to more than one object, so the label
          // it carries here cannot be trusted as an answer key. Counted, named,
          // and kept out of the precision denominator rather than charged to the
          // matcher — which in the case found was demonstrably the correct one.
          tally.groundTruthConflict++;
          stratum.groundTruthConflict++;
          conflicts.push({
            arm, workId: work.id, title: work.title, artist: work.artist_display,
            claimed: truth, got: verdict.qid, claimedBy: work.qid_uses,
          });
        } else {
          // A wrong auto-accept is the expensive failure: §10.2's asymmetry is
          // that it pools two objects' reviews forever and nobody notices.
          tally.acceptedWrong++;
          stratum.acceptedWrong++;
          misses.push({
            arm, workId: work.id, title: work.title, artist: work.artist_display,
            expected: truth, got: verdict.qid, method: verdict.method, score: verdict.score,
          });
        }
      } else if (verdict.outcome === "queued") {
        tally.queued++;
        if (verdict.scored.some((entry) => entry.candidate.qid === truth)) {
          tally.queuedContainingTruth++;
        }
      } else {
        tally.unmatched++;
      }
    }
  }

  const result = {
    generatedAt: new Date().toISOString(),
    source: args.replay ? `replay:${args.replay}` : "wikidata-live",
    sampled: works.length,
    thresholds: { autoAccept: AUTO_ACCEPT, reviewFloor: REVIEW_FLOOR },
    arms: Object.fromEntries(
      Object.entries(tallies).map(([arm, tally]) => [
        arm,
        {
          ...tally,
          precision: precision(tally),
          coverage: coverage(tally),
          // Per arm, because the arms are measured in separate runs.
          measuredAt: new Date().toISOString(),
          source: args.replay ? `replay:${args.replay}` : "wikidata-live",
        },
      ]),
    ),
    misses,
    conflicts,
  };

  if (!args.replay) {
    mkdirSync(path.dirname(args.out), { recursive: true });
    // Summary only. The candidates live in the sidecar, so the committed artifact
    // stays small and readable in a diff.
    writeFileSync(args.out, JSON.stringify(mergeSummary(args.out, result), null, 2));
    checkpoint(args.out, cache, recorded);
  }

  if (args.json) {
    console.log(JSON.stringify(result, null, 2));
    return result;
  }

  const pct = (n) => (n == null ? "  n/a" : `${(n * 100).toFixed(1)}%`);
  console.log(`Reconciliation accuracy · ${result.sampled} real works · ${result.source}`);
  console.log(`  ground truth: the Wikidata Q-number the Met publishes for each object\n`);

  for (const [arm, tally] of Object.entries(result.arms)) {
    const label =
      arm === "accession" ? "accession → label (as shipped)" : "label only (accession withheld)";
    if (!tally.examined) {
      // Nothing was measured for this arm — usually a replay whose cache was built
      // at a different --limit, so the stratified stride selects other works. Say
      // that, rather than print a column of zeros that reads like a result.
      console.log(`${label}\n  not measured in this run (no cached candidates for this sample)\n`);
      continue;
    }
    console.log(`${label}`);
    console.log(`  auto-accepted            ${String(tally.accepted).padStart(4)} of ${tally.examined}`);
    console.log(`    agreed with the museum ${String(tally.acceptedCorrect).padStart(4)}`);
    console.log(`    disagreed              ${String(tally.acceptedWrong).padStart(4)}`);
    if (tally.groundTruthConflict) {
      console.log(`    no usable answer key   ${String(tally.groundTruthConflict).padStart(4)}  (source gave one Q-number to two objects)`);
    }
    console.log(`  queued for a human       ${String(tally.queued).padStart(4)}  (truth among candidates: ${tally.queuedContainingTruth})`);
    console.log(`  no candidate over floor  ${String(tally.unmatched).padStart(4)}`);
    if (tally.errors) console.log(`  errors                   ${String(tally.errors).padStart(4)}`);
    console.log(`  precision  ${pct(tally.precision)}   (of what it decided alone, how much was right)`);
    console.log(`  coverage   ${pct(tally.coverage)}   (of everything sampled, decided AND right)`);
    for (const [name, stratum] of [
      ["named artist", tally.attributed],
      ["anonymous   ", tally.anonymous],
    ]) {
      const p = precision(stratum);
      console.log(
        `    ${name}  ${String(stratum.accepted).padStart(3)}/${String(stratum.examined).padEnd(3)} decided` +
          `   precision ${pct(p)}${stratum.acceptedWrong ? `   wrong ${stratum.acceptedWrong}` : ""}`,
      );
    }
    console.log("");
  }

  if (misses.length) {
    console.log(`Wrong auto-accepts (${misses.length}) — each one pools two objects forever:`);
    for (const miss of misses.slice(0, 10)) {
      console.log(`  [${miss.arm}] ${miss.title} · ${miss.artist}`);
      console.log(`      expected ${miss.expected}, got ${miss.got} (${miss.method}, ${miss.score?.toFixed(3)})`);
    }
  }

  if (conflicts.length) {
    console.log(`\nCatalogue defects (${conflicts.length}) — the source's own answer key disagrees with itself.`);
    console.log(`Not scored against the matcher. Fix the catalogue row:`);
    for (const c of conflicts.slice(0, 10)) {
      console.log(`  [${c.arm}] work ${c.workId} · ${c.title} · ${c.artist}`);
      console.log(`      catalogue says ${c.claimed} (shared by ${c.claimedBy} works), matcher found ${c.got}`);
    }
  }

  return result;
}

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
